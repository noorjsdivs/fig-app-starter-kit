// Generates src/components/icons/glyphs.ts from @material-symbols/svg-500 (Rounded).
// Usage: node tools/build-icons.mjs <design.html> [extra icon names...]
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'node_modules/@material-symbols/svg-500/rounded');
const [, , htmlPath, ...extra] = process.argv;
const names = new Set(extra);

if (htmlPath && fs.existsSync(htmlPath)) {
  const html = fs.readFileSync(htmlPath, 'utf8');
  for (const m of html.matchAll(/>([a-z0-9_]+)<\/span>/g)) names.add(m[1]);
  for (const m of html.matchAll(/'([a-z0-9_]+)'/g)) names.add(m[1]);
}
// Also scan our own source for <Icon name="..."> and icon: '...'
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(d, e.name);
  return e.isDirectory() ? walk(p) : /\.(tsx?|json)$/.test(e.name) ? [p] : [];
});
for (const f of walk(path.join(root, 'src'))) {
  if (f.endsWith('glyphs.ts')) continue;
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/(?:name|icon|Icon)[=:]\s*\{?\s*['"]([a-z0-9_]+)['"]/g)) names.add(m[1]);
  for (const m of src.matchAll(/@icon\s+([a-z0-9_ ]+)/g)) m[1].split(/\s+/).forEach((n) => n && names.add(n));
}

const pathOf = (file) => {
  const svg = fs.readFileSync(file, 'utf8');
  const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  return ds.join(' ');
};
// Legacy ligature names used by the design that were renamed in Material Symbols.
const ALIASES = { expand_more: 'keyboard_arrow_down', local_offer: 'sell', phone_iphone: 'mobile', restaurant_menu: 'restaurant' };
Object.keys(ALIASES).forEach((k) => names.add(k));
const out = {};
for (const n of [...names].sort()) {
  const file = ALIASES[n] || n;
  const o = path.join(dir, file + '.svg');
  const f = path.join(dir, file + '-fill.svg');
  if (!fs.existsSync(o)) continue;
  out[n] = [pathOf(o), fs.existsSync(f) ? pathOf(f) : pathOf(o)];
}
const body = `/* eslint-disable */\n// AUTO-GENERATED by tools/build-icons.mjs — Material Symbols Rounded (weight 500), Apache-2.0.\n// viewBox: 0 -960 960 960. Each entry: [outlined, filled].\nexport const GLYPHS = ${JSON.stringify(out, null, 0).replace(/\],"/g, '],\n"')} as const;\n\nexport type IconName = keyof typeof GLYPHS;\n`;
fs.mkdirSync(path.join(root, 'src/components/icons'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/components/icons/glyphs.ts'), body);
console.log('icons:', Object.keys(out).length, 'bytes:', body.length);
